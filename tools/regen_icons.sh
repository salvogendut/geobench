#!/usr/bin/env bash
# tools/regen_icons.sh - regenerate the committed icon .asm sources from their
# PNGs in assets/, so a *visual* edit to a PNG flows into the desktop's DEFAULT
# icon set on the next build.
#
# The build (tools/build_kernel.sh -> packicons.py) bundles the committed
# lib/icon_*.asm into build/DEFAULT.IST; it does NOT re-run png2cpc, so editing
# a PNG under assets/ alone does nothing. Run this after editing a PNG, then
# rebuild - build_kernel.sh repacks DEFAULT.IST and the card build picks it up.
#
# Each generated icon .asm carries, in its first two lines, the source PNG + size
# and the asm label (written by png2cpc), e.g.
#     ; generated by png2cpc from assets/floppy.png (32x32 px)
#     icon_floppy_w       equ   8 ...
# so this re-runs png2cpc for each using exactly that mapping - re-deriving the
# label from the file (it is NOT always the filename stem: assets/paint/pencil.asm
# uses label icon_pencil). To change an icon: edit its assets/*.png (keep the
# 4-colour desktop palette - see tools/png2cpc.py), run this, rebuild.
#
# Usage:
#   tools/regen_icons.sh                 # every generated icon (lib/ + assets/paint/)
#   tools/regen_icons.sh lib/icon_ide.asm assets/paint/pencil.asm   # just these
set -euo pipefail
cd "$(dirname "$0")/.."

if [ "$#" -gt 0 ]; then
    files=("$@")
else
    files=(lib/icon_*.asm assets/paint/*.asm)
fi

n=0
for asm in "${files[@]}"; do
    [ -f "$asm" ] || { echo "ERROR: no such file: $asm" >&2; exit 1; }
    hdr=$(head -1 "$asm")
    case "$hdr" in
        *"generated by png2cpc from "*) ;;
        *) echo "skip $asm (not a png2cpc-generated icon)"; continue ;;
    esac
    # "; generated by png2cpc from assets/floppy.png (32x32 px)"
    src=${hdr#*from }; src=${src%% (*}
    size=${hdr#*\(};   size=${size%% px)*}        # -> 32x32
    # label = the "<label>_w" symbol on line 2 (NOT the filename stem)
    l2=$(sed -n '2p' "$asm"); tok=${l2%%[[:space:]]*}; label=${tok%_w}
    [ -n "$label" ] || { echo "ERROR: cannot read label from $asm (line 2)" >&2; exit 1; }
    [ -f "$src" ] || { echo "ERROR: source PNG missing: $src (for $asm)" >&2; exit 1; }
    python3 tools/png2cpc.py "$src" "$asm" "$label" "$size"
    n=$((n + 1))
done
echo "regenerated $n icon source(s). Now rebuild:  tools/build_kernel.sh"
